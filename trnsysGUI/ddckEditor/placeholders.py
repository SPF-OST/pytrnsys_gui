import collections.abc as _cabc
import dataclasses as _dc
import re as _re
import typing as _tp

# Placeholder values as produced by the diagram (and as stored in
# `DdckPlaceHolderValues.json`): component name -> port name ->
# port property (e.g. "@temp") -> variable name.
ValuesByPort = _cabc.Mapping[str, _cabc.Mapping[str, str]]
ValuesByComponent = _cabc.Mapping[str, ValuesByPort]

# Mirrors `computed_var` / `computed_output_temp_var` in pytrnsys' ddck
# grammar, e.g. `@temp(In)` or `@mfr(In, MfrDefault)`.
_HYDRAULIC_PLACEHOLDER_REGEX = _re.compile(
    r"@(?P<property>temp|revtemp|mfr|cp|rho)\s*\(\s*"
    r"(?P<port>[A-Za-z]\w*)\s*"
    r"(?:,\s*(?P<default>[A-Za-z]\w*)\s*)?\)"
)

# `@energy(in, heat, Category)` - not provided by the diagram.
_ENERGY_PLACEHOLDER_REGEX = _re.compile(r"@energy\s*\([^)]*\)")


@_dc.dataclass(frozen=True)
class PlaceholderMatch:
    start: int
    end: int
    text: str
    portProperty: str | None  # e.g. "@temp", None for `@energy(...)`
    portName: str | None
    defaultVariableName: str | None

    @property
    def isHydraulic(self) -> bool:
        return self.portProperty is not None


def findPlaceholders(line: str) -> _tp.Sequence[PlaceholderMatch]:
    matches = [
        PlaceholderMatch(
            match.start(),
            match.end(),
            match.group(0),
            "@" + match.group("property"),
            match.group("port"),
            match.group("default"),
        )
        for match in _HYDRAULIC_PLACEHOLDER_REGEX.finditer(line)
    ]

    matches.extend(
        PlaceholderMatch(
            match.start(), match.end(), match.group(0), None, None, None
        )
        for match in _ENERGY_PLACEHOLDER_REGEX.finditer(line)
    )

    return sorted(matches, key=lambda m: m.start)


def findPlaceholderAt(line: str, column: int) -> PlaceholderMatch | None:
    for match in findPlaceholders(line):
        if match.start <= column < match.end:
            return match
    return None


def resolve(
    match: PlaceholderMatch, valuesByPort: ValuesByPort | None
) -> str | None:
    """The variable name the diagram assigns to the placeholder, if any."""
    if not match.isHydraulic or valuesByPort is None:
        return None

    assert match.portName and match.portProperty

    valuesForPort = valuesByPort.get(match.portName)
    if valuesForPort is None:
        return None

    return valuesForPort.get(match.portProperty)


def isUnresolved(
    match: PlaceholderMatch, valuesByPort: ValuesByPort | None
) -> bool:
    """True if the diagram is known and can't provide a value (and there's no
    default in the placeholder itself)."""
    if not match.isHydraulic or valuesByPort is None:
        return False

    if match.defaultVariableName:
        return False

    return resolve(match, valuesByPort) is None


def describe(
    match: PlaceholderMatch, valuesByPort: ValuesByPort | None
) -> str:
    if not match.isHydraulic:
        return (
            f"{match.text}\n"
            "Energy balance variable: its name is generated by pytrnsys."
        )

    if valuesByPort is None:
        default = (
            f" Default: {match.defaultVariableName}."
            if match.defaultVariableName
            else ""
        )
        return (
            f"{match.text}\n"
            "Value unknown: the diagram is not fully connected or this file"
            f" doesn't belong to a component.{default}"
        )

    value = resolve(match, valuesByPort)
    if value is not None:
        return f"{match.text}  →  {value}"

    if match.defaultVariableName:
        return (
            f"{match.text}  →  {match.defaultVariableName} (default: the"
            f" diagram provides no value for port `{match.portName}`)"
        )

    availablePorts = ", ".join(sorted(valuesByPort)) or "none"
    return (
        f"{match.text}\n"
        f"Unresolved: the diagram provides no {match.portProperty} for port"
        f" `{match.portName}`. Available ports: {availablePorts}."
    )
